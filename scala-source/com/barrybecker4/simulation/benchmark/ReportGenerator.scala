package com.barrybecker4.simulation.benchmark

import java.util.Locale

/**
  * Renders the recorded benchmark runs as a markdown report with one table per simulation and one column per
  * label. A strategy that only exists in a newer run shows "n/a" in the older column.
  * Lower fitness is better.
  */
object ReportGenerator {

  val NOT_AVAILABLE = "n/a"
  private val MAX_ERROR_LENGTH = 90

  def render(runs: List[RunRecord]): String = {
    val sb = new StringBuilder
    sb.append("# Simulation optimizer benchmarks\n\n")
    sb.append("Median fitness reached by each bb4-optimization strategy on each simulation, per recorded label.\n")
    sb.append("This file is generated by `./gradlew benchmark` from `benchmarks.json`; do not edit it by hand.\n\n")
    if (runs.isEmpty) {
      sb.append("No results have been recorded yet. Run `./gradlew benchmark` to record a baseline.\n")
    } else {
      appendRuns(sb, runs)
      appendHowToRead(sb)
      appNames(runs).foreach(app => appendApp(sb, app, runs))
    }
    sb.toString
  }

  private def appendRuns(sb: StringBuilder, runs: List[RunRecord]): Unit = {
    sb.append("## Runs\n\n")
    sb.append("| Library | Date | Machine | Time limit | Evaluations | Repetitions |\n")
    sb.append("|---------|------|---------|------------|-------------|-------------|\n")
    runs.foreach { r =>
      val m = r.machine
      sb.append(s"| ${columnTitle(r)} | ${r.timestamp.take(10)} | ${m.cpus} CPUs, ${m.os} ${m.arch}, Java ${m.java}, " +
        s"${m.maxHeapMb} MB heap | ${r.timeoutSeconds}s | ${r.maxEvaluations} | ${r.repetitions} |\n")
    }
    sb.append("\n")
    if (runs.map(_.machine).distinct.size > 1)
      sb.append("**Note:** the runs above were made on different machines, so their timings are not directly comparable.\n\n")
  }

  private def appendHowToRead(sb: StringBuilder): Unit = {
    sb.append("## How to read the tables\n\n")
    sb.append("- A cell is the median fitness of the runs that finished, then the median wall clock time, then how many finished " +
      "(for example `3.14 (1.20 s, 3/3)`). Lower fitness is better.\n")
    sb.append("- `timed out` means no run finished within the time limit. A cell stops early after two runs in a row time out.\n")
    sb.append("- `error: ...` means the search crashed. A cell stops early after two runs in a row fail.\n")
    sb.append(s"- `$NOT_AVAILABLE` means that column did not run this strategy.\n")
    sb.append("- The comparison column is the newest label against the first. For a positive fitness (snake), " +
      "better means a smaller number. For a negative fitness (trebuchet distance), better means a more negative number.\n\n")
  }

  private def appNames(runs: List[RunRecord]): List[String] =
    runs.flatMap(_.results).map(_.app).distinct

  private def appendApp(sb: StringBuilder, app: String, runs: List[RunRecord]): Unit = {
    val rows = rowKeys(app, runs)
    val lookups = runs.map(r => r.results.filter(_.app == app).map(c => ((c.variant, c.algorithm), c)).toMap)
    val compare = runs.size > 1
    sb.append(s"## $app\n\n")
    val titles = runs.map(columnTitle)
    val header = List("App", "Algorithm") ++ titles ++
      (if (compare) List(s"${runs.last.label} vs ${runs.head.label}") else Nil)
    sb.append(header.mkString("| ", " | ", " |\n"))
    sb.append(header.map(_ => "---").mkString("| ", " | ", " |\n"))
    rows.foreach { case (variant, algorithm) =>
      val cells = runs.zip(lookups).map { case (run, byKey) =>
        byKey.get((variant, algorithm)).map(c => cellText(c, run.timeoutSeconds)).getOrElse(NOT_AVAILABLE)
      }
      val change =
        if (compare) List(changeText(lookups.head.get((variant, algorithm)), lookups.last.get((variant, algorithm))))
        else Nil
      sb.append((List(app, s"`$algorithm`") ++ cells ++ change).mkString("| ", " | ", " |\n"))
    }
    sb.append("\n")
  }

  private def rowKeys(app: String, runs: List[RunRecord]): List[(String, String)] = {
    val pairs = runs.flatMap(_.results).filter(_.app == app).map(c => (c.variant, c.algorithm)).distinct
    pairs.map(_._1).distinct.flatMap(variant => pairs.filter(_._1 == variant))
  }

  def columnTitle(run: RunRecord): String = s"${run.libName} ${run.label}"

  def cellText(c: CellResult, timeoutSeconds: Int): String =
    if (c.finished > 0 && c.medianFitness.isDefined && c.medianMillis.isDefined) {
      val fitness = formatFitness(c.medianFitness.get)
      val time = formatMillis(c.medianMillis.get)
      s"$fitness ($time, ${c.finished}/${c.attempts})"
    } else if (c.errored > 0) c.lastError.map(e => s"error: ${shorten(e)}").getOrElse("error")
    else if (c.timedOut > 0) s"timed out after ${timeoutSeconds}s"
    else "no result"

  def formatFitness(fitness: Double): String =
    if (!fitness.isFinite) "inf"
    else if (math.abs(fitness) >= 1000) String.format(Locale.ROOT, "%.0f", java.lang.Double.valueOf(fitness))
    else String.format(Locale.ROOT, "%.2f", java.lang.Double.valueOf(fitness))

  def formatMillis(ms: Long): String =
    if (ms < 1000L) s"$ms ms"
    else if (ms < 60000L) String.format(Locale.ROOT, "%.2f s", java.lang.Double.valueOf(ms / 1000.0))
    else {
      val minutes = ms / 60000L
      val seconds = (ms % 60000L) / 1000L
      val padded = if (seconds < 10L) s"0$seconds" else seconds.toString
      s"${minutes}m ${padded}s"
    }

  /**
    * Compares the first recorded label with the newest one.
    * Lower fitness is better. Positive fitness is a cost (snake). Negative fitness is a negated distance (trebuchet).
    */
  def changeText(baseline: Option[CellResult], newest: Option[CellResult]): String =
    (baseline.flatMap(_.medianFitness), newest.flatMap(_.medianFitness)) match {
      case (Some(before), Some(after)) =>
        val fitness = fitnessChange(before, after)
        val time = (baseline.flatMap(_.medianMillis), newest.flatMap(_.medianMillis)) match {
          case (Some(b), Some(a)) => timeChange(b, a)
          case _ => ""
        }
        if (time.isEmpty) fitness else s"$fitness, $time"
      case (None, Some(_)) => "now finished"
      case (Some(_), None) => "no longer finished"
      case _ => "-"
    }

  private def fitnessChange(before: Double, after: Double): String = {
    if (!before.isFinite || !after.isFinite) "fitness not comparable"
    else if (math.abs(after - before) <= 1e-9 * math.max(1.0, math.abs(before))) "same fitness"
    else {
      val afterBetter = after < before
      val factor =
        if (before > 0 && after > 0) if (afterBetter) before / after else after / before
        else if (before < 0 && after < 0) if (afterBetter) math.abs(after / before) else math.abs(before / after)
        else 0.0
      val word = if (afterBetter) "better fitness" else "worse fitness"
      if (factor >= 1.1) String.format(Locale.ROOT, "%.1fx %s", java.lang.Double.valueOf(factor), word)
      else if (factor == 0.0) word
      else "about the same fitness"
    }
  }

  private def timeChange(before: Long, after: Long): String = {
    val ratio = (before max 1L).toDouble / (after max 1L).toDouble
    if (ratio >= 1.1) String.format(Locale.ROOT, "%.1fx faster", java.lang.Double.valueOf(ratio))
    else if (ratio <= 1.0 / 1.1) String.format(Locale.ROOT, "%.1fx slower", java.lang.Double.valueOf(1.0 / ratio))
    else "similar time"
  }

  private def shorten(message: String): String = {
    val oneLine = message.replace('|', '/').replace('\n', ' ').replace('\r', ' ').trim
    if (oneLine.length <= MAX_ERROR_LENGTH) oneLine else oneLine.take(MAX_ERROR_LENGTH - 3) + "..."
  }
}
